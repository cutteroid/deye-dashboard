"""Air raid alert statuses per region and district (raion) of Ukraine.

Same pattern as outage_providers: a provider fetches statuses, a poller keeps the
latest result in a background thread, and /api/alerts serves it.

Ids come from static/data/ukraine-regions.json (generated by
tools/build_ukraine_map.py):
  - regions:   ISO 3166-2 codes (UA-05 ... UA-77, UA-30 = Kyiv, UA-43 = Crimea)
  - districts: OCHA pcodes (UA0502 ...), each with its region and Ukrainian name
  - both with their alerts.in.ua location UID ("alerts_uid")

Provider contract — fetch() returns
    {"regions":   {region_code:   {"status": str, "since": iso|None}},
     "districts": {district_code: {"status": str, "since": iso|None}}}
(either key may be missing; missing entries count as "none"), where status is:
  - "alert"   air raid alert (red level) in the whole region/district
  - "threat"  threat warning (yellow level), e.g. drones
  - "partial" alert in part of it (some districts/communities)
  - "none"    no alert
and raises AlertsFetchError when statuses can't be obtained.

The poller derives region statuses from districts: a district alert makes its
region "partial" (unless the whole region is under alert), a district threat
makes an otherwise quiet region "threat".
"""
import json
import logging
import os
import random
import re
import threading
import time
from datetime import datetime, timedelta

import requests

logger = logging.getLogger(__name__)

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MAP_FILE = os.path.join(BASE_DIR, "static", "data", "ukraine-regions.json")
REGION_NAMES_FILE = os.path.join(BASE_DIR, "locales", "uk.json")
STATUSES = ("alert", "threat", "partial", "none")

# Statuses older than this (because fetches keep failing) are no longer shown
STATUS_MAX_AGE = timedelta(minutes=5)


def _load_map_ids(path=MAP_FILE):
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    regions = {r["id"]: r.get("alerts_uid") for r in data["regions"]}
    districts = {d["id"]: {"region": d["region"], "name": d["name"]["uk"], "alerts_uid": d.get("alerts_uid")}
                 for d in data["districts"]}
    return regions, districts


# {region_code: alerts.in.ua UID}; {district_code: {"region": code, "name": Ukrainian name, "alerts_uid": UID}}
REGION_UIDS, DISTRICTS = _load_map_ids()
REGION_CODES = tuple(sorted(REGION_UIDS))

# Map areas drawn separately that administratively belong to a raion: they get
# that raion's status. The Chornobyl Exclusion Zone (top of Kyiv oblast) is part
# of Vyshhorodskyi raion since 2020; alert sources report only the raion, and
# NEPTUN's own map colours the zone with it.
DISTRICT_PART_OF = {"UA3200": "UA3210"}


class AlertsFetchError(Exception):
    """Provider could not get alert statuses."""


class AlertsProvider:
    display_name = "alerts"
    is_demo = False

    def fetch(self):
        raise NotImplementedError


class MockAlertsProvider(AlertsProvider):
    """Demo data (AIR_ALERTS_PROVIDER=mock), flagged as demo in the UI.

    Picks pseudo-random region-wide alerts and district alerts/threats per
    5-minute slot, so the map changes over time but stays stable between polls.
    """

    display_name = "Demo data"
    is_demo = True
    SLOT_SECONDS = 300

    def fetch(self):
        slot = int(datetime.now().timestamp()) // self.SLOT_SECONDS
        rng = random.Random(slot)
        since = datetime.fromtimestamp(slot * self.SLOT_SECONDS).isoformat()
        regions = list(REGION_CODES)
        rng.shuffle(regions)
        whole = regions[:rng.randint(1, 3)]
        districts = [d for d in sorted(DISTRICTS) if DISTRICTS[d]["region"] not in whole]
        rng.shuffle(districts)
        picked = districts[:rng.randint(6, 18)]
        return {
            "regions": {code: {"status": "alert", "since": since} for code in whole},
            "districts": {code: {"status": rng.choice(("alert", "threat", "threat")), "since": since}
                          for code in picked},
        }


def normalize_name(name):
    """Comparable place name: "м. Київ" -> "київ", "Куп’янський район" -> "куп'янський"."""
    s = (name or "").strip().lower()
    s = re.sub(r"[’ʼ`´]", "'", s)
    s = re.sub(r"^м\.\s*", "", s)
    s = re.sub(r"\s+(район|область)$", "", s)
    return re.sub(r"\s+", " ", s)


class NeptunProvider(AlertsProvider):
    """NEPTUN public API (https://neptun.in.ua/developers): no key needed.

    GET /api/v1/alerts returns alerting "oblasts" and "raions", each with a
    Ukrainian name, "since" and "level" ("red" = air raid alert, "yellow" =
    threat). Entries are matched to our map by name. Terms of use require a
    visible "Data: ... NEPTUN" link and a note that it's not an official alert
    system — both are shown on the card.
    """

    display_name = "NEPTUN"
    URL = "https://neptun.in.ua/api/v1/alerts"
    LEVEL_STATUS = {"red": "alert", "yellow": "threat"}
    # NEPTUN still uses pre-2024 names for these raions (our map has the new ones)
    RAION_ALIASES = {
        "володимир-волинський": "володимирський",
        "красноградський": "берестинський",
        "новомосковський": "самарівський",
        "сєвєродонецький": "сіверськодонецький",
        "червоноградський": "шептицький",
        "новоград-волинський": "звягельський",
    }

    def __init__(self, timeout=15):
        self.timeout = timeout
        self._session = requests.Session()
        self._etag = None
        self._last_result = None
        with open(REGION_NAMES_FILE, encoding="utf-8") as f:
            region_names = json.load(f)["alerts"]["regions"]
        self._regions_by_name = {normalize_name(name): code for code, name in region_names.items()}
        self._districts_by_name = {normalize_name(d["name"]): code for code, d in DISTRICTS.items()}
        self._warned = set()

    def fetch(self):
        headers = {"If-None-Match": self._etag} if self._etag and self._last_result is not None else {}
        try:
            resp = self._session.get(self.URL, headers=headers, timeout=self.timeout)
        except requests.RequestException as e:
            raise AlertsFetchError(f"NEPTUN request failed: {type(e).__name__}") from e
        if resp.status_code == 304 and self._last_result is not None:
            return self._last_result
        if resp.status_code == 429:
            raise AlertsFetchError("NEPTUN: rate limited (429)")
        if not resp.ok:
            raise AlertsFetchError(f"NEPTUN returned HTTP {resp.status_code}")
        try:
            data = resp.json()
        except ValueError as e:
            raise AlertsFetchError("NEPTUN returned invalid JSON") from e
        if not isinstance(data, dict) or not isinstance(data.get("oblasts"), list) \
                or not isinstance(data.get("raions"), list):
            raise AlertsFetchError("NEPTUN: unexpected response format")

        result = {"regions": {}, "districts": {}}
        for entry in data["oblasts"]:
            code = self._region_code(entry)
            if code:
                result["regions"][code] = self._status(entry)
        for entry in data["raions"]:
            code = self._district_code(entry)
            if code:
                result["districts"][code] = self._status(entry)
        self._etag = resp.headers.get("ETag")
        self._last_result = result
        return result

    def _status(self, entry):
        # Unknown levels count as an alert: better to over- than under-warn
        return {"status": self.LEVEL_STATUS.get(entry.get("level"), "alert"), "since": entry.get("since")}

    def _region_code(self, entry):
        for candidate in (entry.get("name"), entry.get("key")):
            code = self._regions_by_name.get(normalize_name(candidate))
            if code:
                return code
        self._warn_unmatched("oblast", entry)
        return None

    def _district_code(self, entry):
        for candidate in (entry.get("name"), entry.get("key")):
            key = normalize_name(candidate)
            code = self._districts_by_name.get(self.RAION_ALIASES.get(key, key))
            if code:
                return code
        self._warn_unmatched("raion", entry)
        return None

    def _warn_unmatched(self, kind, entry):
        key = (kind, entry.get("key") or entry.get("name"))
        if key not in self._warned:  # once per name, not on every poll
            self._warned.add(key)
            logger.warning("NEPTUN: unknown %s %r, ignored", kind, key[1])


class AlertsInUaProvider(AlertsProvider):
    """alerts.in.ua API (https://devs.alerts.in.ua/), needs a personal token.

    GET /v2/iot/active_air_raid_alerts.json returns one string for all of
    Ukraine with a status character per location, indexed by location UID
    (oblasts, raions and hromadas): "R" air raid alert (red level), "Y" threat
    (yellow level), "P" partial (alert in some of its raions / hromadas), "N" no
    alert, " " no location with this UID. The UIDs of our regions and districts
    are in the map file. The token stays on the server: sent in a header, never
    in the URL, logs or the page. The API answers only requests from Ukraine
    (403 elsewhere).
    """

    display_name = "alerts.in.ua"
    URL = "https://api.alerts.in.ua/v2/iot/active_air_raid_alerts.json"
    CHAR_STATUS = {"R": "alert", "Y": "threat", "P": "partial", "N": "none",
                   "A": "alert"}   # "A" (v1: alert of any level), in case it ever appears

    def __init__(self, token, timeout=15):
        self.token = (token or "").strip()
        self.timeout = timeout
        self._session = requests.Session()
        self._last_modified = None
        self._last_result = None

    def fetch(self):
        if not self.token:
            raise AlertsFetchError("ALERTS_IN_UA_TOKEN is not set")
        headers = {"Authorization": f"Bearer {self.token}"}
        if self._last_modified and self._last_result is not None:
            headers["If-Modified-Since"] = self._last_modified
        try:
            resp = self._session.get(self.URL, headers=headers, timeout=self.timeout)
        except requests.RequestException as e:
            raise AlertsFetchError(f"alerts.in.ua request failed: {type(e).__name__}") from e
        if resp.status_code == 304 and self._last_result is not None:
            return self._last_result
        if resp.status_code == 401:
            raise AlertsFetchError("alerts.in.ua: invalid or missing token (401)")
        if resp.status_code == 403:
            raise AlertsFetchError("alerts.in.ua: access forbidden, IP blocked or outside Ukraine (403)")
        if resp.status_code == 429:
            raise AlertsFetchError("alerts.in.ua: rate limit exceeded (429)")
        if not resp.ok:
            raise AlertsFetchError(f"alerts.in.ua returned HTTP {resp.status_code}")
        statuses = self._status_string(resp)
        if statuses is None:
            raise AlertsFetchError("alerts.in.ua: unexpected response format")

        result = {"regions": self._lookup(statuses, REGION_UIDS),
                  "districts": self._lookup(statuses, {code: d["alerts_uid"] for code, d in DISTRICTS.items()})}
        self._last_modified = resp.headers.get("Last-Modified")
        self._last_result = result
        return result

    @staticmethod
    def _status_string(resp):
        """The status string: documented as JSON ("RNNP..."), accepted bare too.

        Never strip() it: leading spaces are unused UIDs, and every character's
        position is its UID.
        """
        try:
            body = resp.json()
        except ValueError:
            body = (resp.text or "").rstrip("\r\n")
        if not isinstance(body, str) or not body or set(body) - set("RYPNA "):
            return None
        return body

    def _lookup(self, statuses, uids):
        out = {}
        for code, uid in uids.items():
            if uid is None or uid >= len(statuses):
                continue
            status = self.CHAR_STATUS.get(statuses[uid])
            if status:
                out[code] = {"status": status, "since": None}   # the status string has no times
        return out


def create_alerts_provider(name=None, token=None):
    """Provider by name: "alerts_in_ua", "neptun", "mock" (demo data), or "none" to disable.

    Without a name: alerts.in.ua when a token is set, else NEPTUN (no key needed).
    Unknown names disable alerts.
    """
    name = (name or "").strip().lower() or ("alerts_in_ua" if (token or "").strip() else "neptun")
    if name == "none":
        return None
    if name == "mock":
        return MockAlertsProvider()
    if name == "neptun":
        return NeptunProvider()
    if name == "alerts_in_ua":
        return AlertsInUaProvider(token)
    logger.warning("Unknown AIR_ALERTS_PROVIDER=%r, air raid alerts disabled", name)
    return None


def _clean(entries, valid_codes):
    out = {}
    for code, info in (entries or {}).items():
        status = (info or {}).get("status")
        if code in valid_codes and status in STATUSES:
            out[code] = {"status": status, "since": info.get("since")}
        else:
            logger.debug("Ignoring alert entry %r: %r", code, info)
    return out


class AlertsPoller:
    """Polls an alerts provider and keeps the latest statuses."""

    def __init__(self, provider, poll_interval=30):
        self.provider = provider
        self.poll_interval = poll_interval
        self._regions = {}
        self._districts = {}
        self._last_updated = None
        self._last_error = None
        self._lock = threading.Lock()

    def _fetch(self):
        name = type(self.provider).__name__
        try:
            raw = self.provider.fetch() or {}
        except AlertsFetchError as e:
            logger.warning("Air alerts unavailable from %s: %s", name, e)
            with self._lock:
                self._last_error = str(e)
            return
        except Exception as e:
            logger.exception("Error fetching air alerts from %s", name)
            with self._lock:
                self._last_error = f"{type(e).__name__}: {e}"
            return

        regions = _clean(raw.get("regions"), REGION_CODES)
        districts = {code: info for code, info in _clean(raw.get("districts"), DISTRICTS).items()
                     if info["status"] != "none"}
        for part, raion in DISTRICT_PART_OF.items():
            if raion in districts and part not in districts:
                districts[part] = dict(districts[raion])
        # Derive region statuses from districts (alerts take precedence over threats)
        for code, info in sorted(districts.items(), key=lambda kv: kv[1]["status"] != "alert"):
            region = DISTRICTS[code]["region"]
            current = regions.get(region, {}).get("status", "none")
            if info["status"] in ("alert", "partial") and current in ("none", "threat"):
                regions[region] = {"status": "partial", "since": info["since"]}
            elif info["status"] == "threat" and current == "none":
                regions[region] = {"status": "threat", "since": info["since"]}
        with self._lock:
            self._regions = regions
            self._districts = districts
            self._last_updated = datetime.now()
            self._last_error = None

    def get_status(self):
        """{"status": "ok"|"unknown"|"error", "regions": {all codes}, "districts": {alerting only}, ...}."""
        with self._lock:
            regions = dict(self._regions)
            districts = dict(self._districts)
            last_updated = self._last_updated
            last_error = self._last_error

        base = {"provider": self.provider.display_name, "demo": self.provider.is_demo}
        if last_updated is None or datetime.now() - last_updated > STATUS_MAX_AGE:
            if last_error:
                return {**base, "status": "error", "error": last_error}
            return {**base, "status": "unknown"}
        return {
            **base,
            "status": "ok",
            "updated": last_updated.isoformat(),
            "regions": {code: regions.get(code, {"status": "none", "since": None}) for code in REGION_CODES},
            "districts": districts,
        }

    def _run(self):
        while True:
            self._fetch()
            time.sleep(self.poll_interval)

    def start(self):
        threading.Thread(target=self._run, name="air-alerts", daemon=True).start()
